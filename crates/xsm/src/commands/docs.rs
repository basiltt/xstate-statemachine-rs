//! `xsm docs`: a Markdown reference page per machine.

use std::path::PathBuf;

use anyhow::Result;

use super::analysis::{Analysis, analyse};
use super::model::{action_text, file_stem_for, kind_name, policy_rows, short_id, transition_rows};
use crate::output::exit_for;
use crate::ui::Ui;
use xstate_core::Machine;
use xstate_core::machine::NodeKind;

/// Arguments of `docs`.
#[derive(Debug, clap::Args)]
pub(crate) struct DocsArgs {
    /// Machine JSON files.
    #[arg(required = true, value_name = "FILES")]
    files: Vec<PathBuf>,
    /// Directory for `<machine id>.md` pages (default: print to stdout).
    #[arg(short, long, value_name = "DIR")]
    output: Option<PathBuf>,
}

/// Make a value safe inside a Markdown table cell.
fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace(['\n', '\r'], " ")
}

/// Backtick-quoted, comma-joined names; empty when there are none.
fn code_list<'a>(names: impl IntoIterator<Item = &'a str>) -> String {
    names.into_iter().map(|n| format!("`{}`", cell(n))).collect::<Vec<_>>().join(", ")
}

fn states_section(machine: &Machine) -> Vec<String> {
    let mut lines = vec![
        "## States".to_owned(),
        String::new(),
        "| State | Kind | Initial | Entry | Exit | Timers | Invokes | Tags |".to_owned(),
        "|---|---|---|---|---|---|---|---|".to_owned(),
    ];
    for node in machine.states().iter().skip(1) {
        let initial = match &node.kind {
            NodeKind::Compound { initial } => format!("`{}`", machine.node(*initial).key),
            _ => String::new(),
        };
        let entry: Vec<String> = node.entry.iter().map(action_text).collect();
        let exit: Vec<String> = node.exit.iter().map(action_text).collect();
        lines.push(format!(
            "| `{}` | {} | {} | {} | {} | {} | {} | {} |",
            cell(short_id(machine, &node.id)),
            kind_name(&node.kind),
            initial,
            code_list(entry.iter().map(String::as_str)),
            code_list(exit.iter().map(String::as_str)),
            cell(&node.after.iter().map(|a| a.key.as_str()).collect::<Vec<_>>().join(", ")),
            code_list(node.invokes.iter().map(|i| i.src.as_str())),
            code_list(node.tags.iter().map(String::as_str)),
        ));
    }
    lines
}

fn transitions_section(machine: &Machine) -> Vec<String> {
    let mut lines = vec![
        "## Transitions".to_owned(),
        String::new(),
        "| Event | From | To | Guard | Actions |".to_owned(),
        "|---|---|---|---|---|".to_owned(),
    ];
    for row in transition_rows(machine) {
        let to = row
            .to
            .split(", ")
            .map(
                |t| if t.starts_with('(') { t.to_owned() } else { short_id(machine, t).to_owned() },
            )
            .collect::<Vec<_>>()
            .join(", ");
        let guard =
            if row.guard.is_empty() { String::new() } else { format!("`{}`", cell(&row.guard)) };
        let actions =
            if row.actions.is_empty() { String::new() } else { code_list(row.actions.split(", ")) };
        lines.push(format!(
            "| `{}` | `{}` | `{}` | {} | {} |",
            cell(&row.event),
            cell(short_id(machine, &row.from)),
            cell(&to),
            guard,
            actions
        ));
    }
    lines
}

fn logic_section(analysis: &Analysis) -> Vec<String> {
    let mut lines = vec!["## Logic to implement".to_owned(), String::new()];
    let logic = &analysis.logic;
    for (title, names) in [
        ("Actions", &logic.actions),
        ("Guards", &logic.guards),
        ("Services", &logic.services),
        ("Named delays", &logic.delays),
    ] {
        if !names.is_empty() {
            lines.push(format!("**{title}:** {}", code_list(names.iter().map(String::as_str))));
            lines.push(String::new());
        }
    }
    lines
}

/// Render the Markdown page for one analysed machine.
fn render_page(analysis: &Analysis, machine: &Machine) -> String {
    let (nested, _) = analysis.state_counts();
    let file_name =
        analysis.file.file_name().map_or_else(String::new, |n| n.to_string_lossy().into_owned());
    let logic = &analysis.logic;
    let mut lines = vec![
        format!("# `{}`", machine.id()),
        String::new(),
        format!(
            "> Generated by `xsm docs` from `{file_name}`. {nested} states, {} events, \
             {} actions, {} guards, {} services.",
            machine.declared_events().len(),
            logic.actions.len(),
            logic.guards.len(),
            logic.services.len()
        ),
        String::new(),
        "## Diagram".to_owned(),
        String::new(),
        "```mermaid".to_owned(),
        machine.to_mermaid(),
        "```".to_owned(),
        String::new(),
    ];
    lines.extend(states_section(machine));
    lines.push(String::new());
    lines.extend(transitions_section(machine));
    lines.push(String::new());
    lines.extend(logic_section(analysis));
    lines.extend([
        "## Policies".to_owned(),
        String::new(),
        "| Key | Value |".to_owned(),
        "|---|---|".to_owned(),
    ]);
    lines.extend(policy_rows(machine).into_iter().map(|(k, v)| format!("| `{k}` | `{v}` |")));
    let warnings: Vec<_> = analysis.warnings().collect();
    if !warnings.is_empty() {
        lines.extend([String::new(), "## Warnings".to_owned(), String::new()]);
        for w in warnings {
            let at = if w.path.is_empty() { String::new() } else { format!(" (`{}`)", w.path) };
            lines.push(format!("- {}{at}", w.message));
        }
    }
    lines.extend([String::new(), "## Events".to_owned(), String::new()]);
    lines.push(code_list(machine.declared_events().iter().map(String::as_str)));
    lines.push(String::new());
    lines.join("\n")
}

/// Run `docs`; exit 1 when any file could not be documented.
pub(crate) fn run(ui: Ui, args: &DocsArgs) -> Result<u8> {
    let mut written = 0usize;
    let mut failed = 0usize;
    for file in &args.files {
        let analysis = analyse(ui, file, true, true);
        let Some(machine) = analysis.machine.as_ref() else {
            // One broken file must not stop the others from being documented.
            eprintln!("xsm: error: {}", analysis.first_error());
            failed += 1;
            continue;
        };
        let page = render_page(&analysis, machine);
        let Some(dir) = &args.output else {
            println!("{page}");
            continue;
        };
        std::fs::create_dir_all(dir)?;
        let target = dir.join(format!("{}.md", file_stem_for(machine.id())));
        std::fs::write(&target, format!("{page}\n"))?;
        println!("Wrote {}", target.display());
        written += 1;
    }
    if args.output.is_some() {
        println!("{written} page(s) written");
    }
    if failed > 0 {
        eprintln!("xsm: error: {failed} file(s) could not be documented");
    }
    Ok(exit_for(failed == 0))
}
