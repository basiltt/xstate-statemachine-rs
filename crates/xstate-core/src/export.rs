//! Exporters: the machine back to XState JSON, Mermaid `stateDiagram-v2` and `PlantUML`.
//!
//! * JSON: [`Machine::to_json`] / [`Machine::to_json_string`] return the configuration
//!   document the machine was compiled from, verbatim, so `Machine::from_value(&m.to_json())`
//!   round-trips.
//! * Diagrams: [`to_mermaid`] and [`to_plantuml`] (also available as [`Machine::to_mermaid`]
//!   and [`Machine::to_plantuml`]) reproduce the output of the Python library's
//!   `MachineNode.to_mermaid()` / `to_plantuml()` byte for byte for every machine whose state
//!   keys are plain identifiers; the conformance fixtures under `tests/fixtures/export` are
//!   generated by the Python implementation.
//!
//! # Conventions (shared with Python)
//!
//! * Every state is declared as `state "<key>" as <id>`; compound and parallel states open a
//!   `{ ... }` block holding `[*] --> <initial>` (compound only), their children, and a lone
//!   `--` line between the regions of a parallel state. Final states are followed by
//!   `<id> --> [*]` (never for the root). History pseudo-states are drawn as plain states.
//! * The diagram opens with the root's initial marker (`[*] --> <root>` in Mermaid,
//!   `[*] --> <initial child>` in `PlantUML`, after the declarations).
//! * Edges are emitted per state in document (pre-)order. Per state: `on` events (labelled with
//!   the v4 spelling of engine events, e.g. `done.invoke.x`), eventless transitions (`always`),
//!   the compound `onDone` (every alternative, unguarded label `onDone`), `after`
//!   transitions (`after 500ms`, or `after NAME` for a named delay), then invoke completions
//!   (`invoke onDone`, `invoke onError`). Everything but `on` and `onDone` labels gets a
//!   ` [guard]` suffix when guarded (composite guards show as `and` / `or` / `not`).
//!   Targetless and forbidden transitions are skipped, and only the first target of a
//!   multi-target transition is drawn (Python has no multi-target transitions at all).
//!
//! # Known differences from Python
//!
//! * **Identifier safety.** Python writes state keys into the diagram unescaped. Here a Mermaid
//!   id that is not `[A-Za-z0-9_]+` (or that collides with a Mermaid keyword such as `end` or
//!   `state`) is sanitised to `_` and suffixed with the state's arena index so distinct states
//!   stay distinct; the original key is kept as the quoted display name (`"` becomes
//!   `#quot;`). The same applies to `PlantUML` ids (alphanumerics and `_` are kept, as is `.` which
//!   becomes `_`, exactly like Python). Edge labels lose line breaks, and `;` becomes `#59;` in
//!   Mermaid.
//! * **Mermaid ids are local keys**, as in Python, so repeated keys at different depths still
//!   collide in Mermaid (use distinct keys for an unambiguous diagram). `PlantUML` ids are full
//!   dotted ids and never collide.
//! * **`always` position.** Python places the eventless bucket where the `""` key appears in
//!   `on`; here it always follows the named `on` events.
//! * **Raw event spelling.** Python prints the event key exactly as written; here engine events
//!   are normalised first and printed back in the v4 spelling, which is identical unless the
//!   document spells an engine event with its v5 name (`xstate.done.actor.x`).

use crate::event::names;
use crate::ids::StateId;
use crate::machine::{Guard, Machine, NodeKind, Transition, Trigger};
use crate::snapshot::python_event_name;

/// Mermaid keywords that cannot be used as bare state ids.
const MERMAID_RESERVED: [&str; 11] = [
    "state",
    "end",
    "note",
    "direction",
    "class",
    "classDef",
    "style",
    "click",
    "default",
    "scale",
    "hide",
];

/// Rendering a machine as a Mermaid `stateDiagram-v2` document.
#[must_use]
pub fn to_mermaid(machine: &Machine) -> String {
    let style = Style {
        step: 4,
        id: mermaid_id,
        name: |s| single_line(s).replace('"', "#quot;"),
        label: |s| single_line(s).replace(';', "#59;"),
    };
    let mut out = vec!["stateDiagram-v2".to_owned()];
    if let NodeKind::Compound { .. } = machine.node(StateId::ROOT).kind {
        out.push(format!("[*] --> {}", mermaid_id(machine, StateId::ROOT)));
    }
    emit_state(&style, machine, StateId::ROOT, 0, &mut out);
    emit_edges(&style, machine, &mut out);
    out.join("\n")
}

/// Rendering a machine as a `PlantUML` state diagram.
#[must_use]
pub fn to_plantuml(machine: &Machine) -> String {
    let style = Style {
        step: 2,
        id: plantuml_id,
        name: |s| single_line(s).replace('"', "'"),
        label: |s| single_line(s).into_owned(),
    };
    let mut out = vec!["@startuml".to_owned(), "hide empty description".to_owned()];
    emit_state(&style, machine, StateId::ROOT, 0, &mut out);
    if let NodeKind::Compound { initial } = machine.node(StateId::ROOT).kind {
        out.push(format!("[*] --> {}", plantuml_id(machine, initial)));
    }
    emit_edges(&style, machine, &mut out);
    out.push("@enduml".to_owned());
    out.join("\n")
}

/// The per-dialect knobs of the shared renderer.
struct Style {
    /// Indentation per nesting level.
    step: usize,
    /// Diagram identifier of a state.
    id: fn(&Machine, StateId) -> String,
    /// Escapes a state key for use inside `state "..."`.
    name: fn(&str) -> String,
    /// Escapes an edge label.
    label: fn(&str) -> String,
}

/// One drawn transition.
struct Edge {
    target: StateId,
    label: String,
}

fn emit_state(style: &Style, machine: &Machine, sid: StateId, level: usize, out: &mut Vec<String>) {
    let node = machine.node(sid);
    let indent = " ".repeat(style.step * level);
    let id = (style.id)(machine, sid);
    let name = (style.name)(&node.key);
    if node.children.is_empty() {
        out.push(format!("{indent}state \"{name}\" as {id}"));
        if node.is_final() && node.parent.is_some() {
            out.push(format!("{indent}{id} --> [*]"));
        }
        return;
    }
    let inner = " ".repeat(style.step * (level + 1));
    out.push(format!("{indent}state \"{name}\" as {id} {{"));
    if let NodeKind::Compound { initial } = node.kind {
        out.push(format!("{inner}[*] --> {}", (style.id)(machine, initial)));
    }
    let is_parallel = node.is_parallel();
    for (index, &child) in node.children.iter().enumerate() {
        if index > 0 && is_parallel {
            out.push(format!("{inner}--"));
        }
        emit_state(style, machine, child, level + 1, out);
    }
    out.push(format!("{indent}}}"));
}

fn emit_edges(style: &Style, machine: &Machine, out: &mut Vec<String>) {
    let mut by_source: Vec<Vec<&Transition>> = vec![Vec::new(); machine.states().len()];
    for t in machine.transitions() {
        by_source[t.source.index()].push(t);
    }
    for (index, transitions) in by_source.iter().enumerate() {
        let source = StateId::from_index(index);
        let from = (style.id)(machine, source);
        for edge in node_edges(machine, source, transitions) {
            let to = (style.id)(machine, edge.target);
            out.push(format!("{from} --> {to} : {}", (style.label)(&edge.label)));
        }
    }
}

/// Labelled outgoing edges of one state, in the order Python draws them.
fn node_edges(machine: &Machine, sid: StateId, transitions: &[&Transition]) -> Vec<Edge> {
    let node = machine.node(sid);
    let done_state = names::done_state(&node.id);
    let mut ranked: Vec<((u8, usize), &Transition, String)> = Vec::new();
    for &t in transitions {
        let (rank, label) = match &t.trigger {
            Trigger::Always => ((1, 0), guarded("always", t)),
            Trigger::Event(e) if *e == done_state => ((2, 0), "onDone".to_owned()),
            Trigger::Event(e) => {
                if let Some(i) = node.after.iter().position(|a| a.event == e.as_str()) {
                    let suffix = delay_suffix(&node.after[i].key);
                    ((3, i), guarded(&format!("after {suffix}"), t))
                } else if let Some(i) =
                    node.invokes.iter().position(|v| names::done_actor(&v.id) == e.as_str())
                {
                    ((4, 2 * i), guarded("invoke onDone", t))
                } else if let Some(i) =
                    node.invokes.iter().position(|v| names::error_actor(&v.id) == e.as_str())
                {
                    ((4, 2 * i + 1), guarded("invoke onError", t))
                } else {
                    ((0, 0), python_event_name(e))
                }
            }
        };
        ranked.push((rank, t, label));
    }
    ranked.sort_by_key(|(rank, _, _)| *rank);
    let mut edges = Vec::new();
    for (_, t, label) in ranked {
        if let Some(&target) = t.targets.first() {
            edges.push(Edge { target, label });
        }
    }
    edges
}

/// `after` key to the label suffix: integers print as `<n>ms`, names verbatim.
fn delay_suffix(key: &str) -> String {
    key.trim().parse::<i64>().map_or_else(|_| key.to_owned(), |ms| format!("{ms}ms"))
}

fn guarded(label: &str, t: &Transition) -> String {
    match t.guard.as_ref() {
        Some(g) => format!("{label} [{}]", guard_name(g)),
        None => label.to_owned(),
    }
}

/// The guard's `type`, which is what Python prints.
fn guard_name(guard: &Guard) -> &str {
    match guard {
        Guard::Named { name, .. } => name,
        Guard::StateIn { .. } => "stateIn",
        Guard::Not(_) => "not",
        Guard::And(_) => "and",
        Guard::Or(_) => "or",
    }
}

fn single_line(text: &str) -> std::borrow::Cow<'_, str> {
    if text.contains(['\n', '\r']) {
        std::borrow::Cow::Owned(text.replace(['\n', '\r'], " "))
    } else {
        std::borrow::Cow::Borrowed(text)
    }
}

/// Mermaid id: the local key when it is a plain identifier (as Python), otherwise a sanitised
/// form made unique with the arena index.
fn mermaid_id(machine: &Machine, sid: StateId) -> String {
    let key = machine.node(sid).key.as_str();
    let plain = !key.is_empty() && key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
    let reserved = MERMAID_RESERVED.iter().any(|k| k.eq_ignore_ascii_case(key));
    if plain && !reserved {
        return key.to_owned();
    }
    let cleaned: String =
        key.chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '_' }).collect();
    format!("{cleaned}_{}", sid.index())
}

/// `PlantUML` id: the dotted id with `.` as `_` (as Python); other unsafe characters are
/// replaced too, and the result is made unique with the arena index when that happened.
fn plantuml_id(machine: &Machine, sid: StateId) -> String {
    let full = &*machine.node(sid).id;
    let mut changed = false;
    let cleaned: String = full
        .chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '_' {
                c
            } else {
                changed |= c != '.';
                '_'
            }
        })
        .collect();
    if changed { format!("{cleaned}_{}", sid.index()) } else { cleaned }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn machine(value: &serde_json::Value) -> Machine {
        Machine::from_value(value).expect("valid machine")
    }

    #[test]
    fn mermaid_escapes_unsafe_ids_and_keeps_labels() {
        let m = machine(&json!({
            "id": "m", "initial": "end",
            "states": {
                "end": { "on": { "GO": "say \"hi\"" } },
                "say \"hi\"": { "on": { "BACK;NOW": "end" } },
                "日本": {}
            }
        }));
        let text = m.to_mermaid();
        assert!(text.contains("state \"end\" as end_1"), "{text}");
        assert!(text.contains("state \"say #quot;hi#quot;\" as say__hi__2"), "{text}");
        assert!(text.contains("end_1 --> say__hi__2 : GO"), "{text}");
        assert!(text.contains("say__hi__2 --> end_1 : BACK#59;NOW"), "{text}");
        for line in text.lines().filter(|l| l.contains(" as ")) {
            let id = line.rsplit(" as ").next().unwrap_or_default().trim_end_matches(" {");
            assert!(id.chars().all(|c| c.is_ascii_alphanumeric() || c == '_'), "{line}");
        }
    }

    #[test]
    fn plantuml_escapes_unsafe_ids() {
        let m = machine(&json!({
            "id": "m", "initial": "a b",
            "states": { "a b": { "on": { "GO": "c\"d" } }, "c\"d": {} }
        }));
        let text = m.to_plantuml();
        assert!(text.contains("state \"a b\" as m_a_b_1"), "{text}");
        assert!(text.contains("state \"c'd\" as m_c_d_2"), "{text}");
        assert!(text.contains("m_a_b_1 --> m_c_d_2 : GO"), "{text}");
    }

    #[test]
    fn delay_suffix_formats_numbers_and_names() {
        assert_eq!(delay_suffix("500"), "500ms");
        assert_eq!(delay_suffix("BACKOFF"), "BACKOFF");
    }
}
